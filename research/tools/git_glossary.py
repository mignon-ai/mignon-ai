def normalize(cmd):
    """Skeleton of a command: subcommand and flags, with names, paths and values removed."""
    toks = []
    for t in cmd.replace("&&", " && ").split():
        t = t.strip("'\"")
        if t == "git" or t == "&&" or t.startswith("-"):
            toks.append(t.split("=")[0])
        elif not toks or toks[-1] == "git" or toks[-1] == "&&":
            toks.append(t)
    return " ".join(toks)


def eval_skeletons(path):
    skeletons = set()
    for task in json.load(open(path)):
        for exp in task.get("expected", []):
            cmd = (task.get("prompt", "") + exp).strip()
            if cmd.startswith("git "):
                skeletons.add(normalize(cmd))
    return skeletons


def fill(template, rng):
    values = {}
    for key, pool in POOLS.items():
        values[key] = rng.choice(pool)
    # distinct second names
    values["b2"] = rng.choice([x for x in POOLS["b"] if x != values["b"]])
    values["f2"] = rng.choice([x for x in POOLS["f"] if x != values["f"]])
    return values


def render(text, values):
    return re.sub(r"\{(\w+)\}", lambda m: values.get(m.group(1), m.group(0)), text)


def build(eval_path, seed=7):
    rng = random.Random(seed)
    banned = eval_skeletons(eval_path)
    train, heldout, overlap = [], [], []
    for command, requests in G:
        skeleton = normalize(command)
        bucket = train
        if skeleton in banned:
            bucket = overlap
        elif int(hashlib.sha256(command.encode()).hexdigest(), 16) % HELDOUT_EVERY == 0:
            bucket = heldout
        for request in requests:
            for _ in range(VARIANTS_PER_PHRASING):
                values = fill(command, rng)
                bucket.append({"instruction": render(request, values), "output": render(command, values)})
    return train, heldout, overlap


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="data")
    ap.add_argument("--eval", default="research/eval/git_tasks.json")
    args = ap.parse_args()
    train, heldout, overlap = build(args.eval)
    for name, rows in [("git_glossary_train.json", train), ("git_glossary_heldout.json", heldout),
                       ("git_glossary_eval_overlap.json", overlap)]:
        with open(os.path.join(args.out_dir, name), "w") as f:
            json.dump(rows, f, indent=1)
        print(f"{name}: {len(rows)} pairs")


if __name__ == "__main__":
    main()
