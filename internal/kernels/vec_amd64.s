// Constants for fast single-precision exp:
// invLn2 = 1.4426950408889634 -> 0x3fb8aa3b
// ln2Hi  = 0.693145751953125   -> 0x3f317200
// ln2Lo  = 1.4286068203094172e-06 -> 0x35bfbe8e
// c2 = 0.5           -> 0x3f000000
// c3 = 0.16666667    -> 0x3e2aaaab
// c4 = 0.041666668   -> 0x3d2aaaab
// c5 = 0.008333334   -> 0x3c088889
// one = 1.0          -> 0x3f800000
// maxVal = 88.0      -> 0x42b00000
// minVal = -88.0     -> 0xc2b00000

// func vecExpASM_F32(dst, src []float32)
TEXT ·vecExpASM_F32(SB), NOSPLIT, $0-48
	MOVQ dst_base+0(FP), DI
	MOVQ dst_len+8(FP), CX
	MOVQ src_base+24(FP), SI
	MOVQ src_len+32(FP), DX

	CMPQ DX, CX
	JGE have_len_exp_f32
	MOVQ DX, CX
have_len_exp_f32:
	CMPQ CX, $0
	JLE done_exp_f32

	VZEROUPPER
	// Load scalar constants into registers
	MOVL $0x3fb8aa3b, AX // invLn2
	VMOVD AX, X14
	VBROADCASTSS X14, Y14

	MOVL $0x3f317200, AX // ln2Hi (musl exact float32)
	VMOVD AX, X15
	VBROADCASTSS X15, Y15

	MOVL $0x35bfbe8e, AX // ln2Lo (musl)
	VMOVD AX, X13
	VBROADCASTSS X13, Y13

	MOVL $0x3f800000, AX // 1.0
	VMOVD AX, X12
	VBROADCASTSS X12, Y12

loop8_exp_f32:
	CMPQ CX, $8
	JL scalar_loop_exp_f32

	VMOVUPS 0(SI), Y0 // x

	// Clamp to [-88, 88] to prevent overflow/underflow
	MOVL $0x42b00000, AX
	VMOVD AX, X1
	VBROADCASTSS X1, Y1
	VMINPS Y1, Y0, Y0
	MOVL $0xc2b00000, AX
	VMOVD AX, X1
	VBROADCASTSS X1, Y1
	VMAXPS Y1, Y0, Y0

	// k = round(x * invLn2)
	VMULPS Y14, Y0, Y1
	VROUNDPS $0x00, Y1, Y1 // round to nearest even (k)

	// r = x - k*ln2Hi - k*ln2Lo
	VMOVAPS Y0, Y2
	VFNMADD231PS Y15, Y1, Y2 // Y2 = Y0 - Y1*ln2Hi
	VFNMADD231PS Y13, Y1, Y2 // Y2 = r = (x - k*ln2Hi) - k*ln2Lo

	// 5th-degree Minimax polynomial: 1 + r*(1 + r*(c2 + r*(c3 + r*(c4 + r*c5))))
	MOVL $0x3c088889, AX // c5
	VMOVD AX, X3
	VBROADCASTSS X3, Y3

	MOVL $0x3d2aaaab, AX // c4
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3 // Y3 = r*c5 + c4

	MOVL $0x3e2aaaab, AX // c3
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3 // Y3 = r*(r*c5 + c4) + c3

	MOVL $0x3f000000, AX // c2
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3 // Y3 = r*(...) + c2

	VFMADD213PS Y12, Y2, Y3 // Y3 = r*(...) + 1.0 (since 1.0 is in Y12)
	VFMADD213PS Y12, Y2, Y3 // Y3 = poly = r*(...) + 1.0

	// 2^k scaling: integer exponent adjustment
	VCVTPS2DQ Y1, Y4
	VPADDD exp_bias<>(SB), Y4, Y4
	VPSLLD $23, Y4, Y4 // Y4 = 2^k

	VMULPS Y4, Y3, Y0 // result = poly * 2^k

	VMOVUPS Y0, 0(DI)
	ADDQ $32, SI
	ADDQ $32, DI
	SUBQ $8, CX
	JMP loop8_exp_f32

scalar_loop_exp_f32:
	TESTQ CX, CX
	JZ done_exp_f32

	VMOVSS 0(SI), X0
	// Inline scalar fast exp
	MOVL $0x42b00000, AX
	VMOVD AX, X1
	VMINSS X1, X0, X0
	MOVL $0xc2b00000, AX
	VMOVD AX, X1
	VMAXSS X1, X0, X0

	MOVL $0x3fb8aa3b, AX
	VMOVD AX, X14
	VMULSS X14, X0, X1
	VROUNDSS $0x00, X1, X1, X1 // k

	MOVL $0x3f317200, AX
	VMOVD AX, X15
	MOVL $0x35bfbe8e, AX
	VMOVD AX, X13
	VMOVAPS X0, X2
	VFNMADD231SS X15, X1, X2
	VFNMADD231SS X13, X1, X2 // r

	MOVL $0x3c088889, AX
	VMOVD AX, X3
	MOVL $0x3d2aaaab, AX
	VMOVD AX, X4
	VFMADD213SS X4, X2, X3
	MOVL $0x3e2aaaab, AX
	VMOVD AX, X4
	VFMADD213SS X4, X2, X3
	MOVL $0x3f000000, AX
	VMOVD AX, X4
	VFMADD213SS X4, X2, X3
	MOVL $0x3f800000, AX
	VMOVD AX, X12
	VFMADD213SS X12, X2, X3
	VFMADD213SS X12, X2, X3 // poly

	VCVTTSS2SI X1, AX
	ADDL $127, AX
	SHLL $23, AX
	VMOVD AX, X4
	VMULSS X4, X3, X0

	VMOVSS X0, 0(DI)
	ADDQ $4, SI
	ADDQ $4, DI
	DECQ CX
	JNZ scalar_loop_exp_f32

done_exp_f32:
	VZEROUPPER
	RET

// func vecSigmoidASM_F32(dst, src []float32)
TEXT ·vecSigmoidASM_F32(SB), NOSPLIT, $0-48
	MOVQ dst_base+0(FP), DI
	MOVQ dst_len+8(FP), CX
	MOVQ src_base+24(FP), SI
	MOVQ src_len+32(FP), DX

	CMPQ DX, CX
	JGE have_len_sig_f32
	MOVQ DX, CX
have_len_sig_f32:
	CMPQ CX, $0
	JLE done_sig_f32

	VZEROUPPER
	MOVL $0x3fb8aa3b, AX // invLn2
	VMOVD AX, X14
	VBROADCASTSS X14, Y14

	MOVL $0x3f317200, AX // ln2Hi (musl exact float32)
	VMOVD AX, X15
	VBROADCASTSS X15, Y15

	MOVL $0x35bfbe8e, AX // ln2Lo (musl)
	VMOVD AX, X13
	VBROADCASTSS X13, Y13

	MOVL $0x3f800000, AX // 1.0
	VMOVD AX, X12
	VBROADCASTSS X12, Y12

	VXORPS Y11, Y11, Y11 // 0.0

loop8_sig_f32:
	CMPQ CX, $8
	JL scalar_loop_sig_f32

	VMOVUPS 0(SI), Y0 // x

	// Negate: Y0 = -x
	VSUBPS Y0, Y11, Y0

	// Clamp to [-88, 88]
	MOVL $0x42b00000, AX
	VMOVD AX, X1
	VBROADCASTSS X1, Y1
	VMINPS Y1, Y0, Y0
	MOVL $0xc2b00000, AX
	VMOVD AX, X1
	VBROADCASTSS X1, Y1
	VMAXPS Y1, Y0, Y0

	// k = round(-x * invLn2)
	VMULPS Y14, Y0, Y1
	VROUNDPS $0x00, Y1, Y1

	// r = (-x) - k*ln2Hi - k*ln2Lo
	VMOVAPS Y0, Y2
	VFNMADD231PS Y15, Y1, Y2
	VFNMADD231PS Y13, Y1, Y2

	// Minimax poly
	MOVL $0x3c088889, AX
	VMOVD AX, X3
	VBROADCASTSS X3, Y3
	MOVL $0x3d2aaaab, AX
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3
	MOVL $0x3e2aaaab, AX
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3
	MOVL $0x3f000000, AX
	VMOVD AX, X4
	VBROADCASTSS X4, Y4
	VFMADD213PS Y4, Y2, Y3
	VFMADD213PS Y12, Y2, Y3
	VFMADD213PS Y12, Y2, Y3 // poly

	// 2^k
	VCVTPS2DQ Y1, Y4
	VPADDD exp_bias<>(SB), Y4, Y4
	VPSLLD $23, Y4, Y4
	VMULPS Y4, Y3, Y0 // expVal = e^(-x)

	// sigmoid = 1.0 / (1.0 + expVal)
	VADDPS Y12, Y0, Y0
	VDIVPS Y0, Y12, Y0

	VMOVUPS Y0, 0(DI)
	ADDQ $32, SI
	ADDQ $32, DI
	SUBQ $8, CX
	JMP loop8_sig_f32

scalar_loop_sig_f32:
	TESTQ CX, CX
	JZ done_sig_f32

	VMOVSS 0(SI), X0
	VXORPS X1, X1, X1
	VSUBSS X0, X1, X1 // -x

	MOVL $0x42b00000, AX
	VMOVD AX, X2
	VMINSS X2, X1, X1
	MOVL $0xc2b00000, AX
	VMOVD AX, X2
	VMAXSS X2, X1, X1

	MOVL $0x3fb8aa3b, AX
	VMOVD AX, X14
	VMULSS X14, X1, X2
	VROUNDSS $0x00, X2, X2, X2 // k

	MOVL $0x3f317200, AX
	VMOVD AX, X15
	MOVL $0x35bfbe8e, AX
	VMOVD AX, X13
	VMOVAPS X1, X0
	VFNMADD231SS X15, X2, X0
	VFNMADD231SS X13, X2, X0 // r

	MOVL $0x3c088889, AX
	VMOVD AX, X3
	MOVL $0x3d2aaaab, AX
	VMOVD AX, X4
	VFMADD213SS X4, X0, X3
	MOVL $0x3e2aaaab, AX
	VMOVD AX, X4
	VFMADD213SS X4, X0, X3
	MOVL $0x3f000000, AX
	VMOVD AX, X4
	VFMADD213SS X4, X0, X3
	MOVL $0x3f800000, AX
	VMOVD AX, X12
	VFMADD213SS X12, X0, X3
	VFMADD213SS X12, X0, X3 // poly

	VCVTTSS2SI X2, AX
	ADDL $127, AX
	SHLL $23, AX
	VMOVD AX, X4
	VMULSS X4, X3, X0 // expVal

	VADDSS X12, X0, X0
	VDIVSS X0, X12, X0
	VMOVSS X0, 0(DI)

	ADDQ $4, SI
	ADDQ $4, DI
	DECQ CX
	JNZ scalar_loop_sig_f32

done_sig_f32:
	VZEROUPPER
	RET

