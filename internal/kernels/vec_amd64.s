// func dotInt8ASM_F32(x []float32, w []int8) float32
// Sign-extends 8 int8 weights to int32, converts them to float32 and accumulates x·w with FMA.
TEXT ·dotInt8ASM_F32(SB), NOSPLIT, $0-52
	MOVQ x_base+0(FP), SI
	MOVQ x_len+8(FP), CX
	MOVQ w_base+24(FP), DI
	MOVQ w_len+32(FP), DX

	CMPQ DX, CX
	JGE have_len_i8
	MOVQ DX, CX
have_len_i8:
	VZEROUPPER
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5

loop32_i8:
	CMPQ CX, $32
	JL loop8_i8
	VPMOVSXBD 0(DI), Y2
	VPMOVSXBD 8(DI), Y3
	VPMOVSXBD 16(DI), Y6
	VPMOVSXBD 24(DI), Y7
	VCVTDQ2PS Y2, Y2
	VCVTDQ2PS Y3, Y3
	VCVTDQ2PS Y6, Y6
	VCVTDQ2PS Y7, Y7
	VFMADD231PS 0(SI), Y2, Y0
	VFMADD231PS 32(SI), Y3, Y1
	VFMADD231PS 64(SI), Y6, Y4
	VFMADD231PS 96(SI), Y7, Y5
	ADDQ $128, SI
	ADDQ $32, DI
	SUBQ $32, CX
	JMP loop32_i8

loop8_i8:
	CMPQ CX, $8
	JL reduce_i8
	VPMOVSXBD 0(DI), Y2
	VCVTDQ2PS Y2, Y2
	VFMADD231PS 0(SI), Y2, Y0
	ADDQ $32, SI
	ADDQ $8, DI
	SUBQ $8, CX
	JMP loop8_i8

reduce_i8:
	VADDPS Y1, Y0, Y0
	VADDPS Y5, Y4, Y4
	VADDPS Y4, Y0, Y0
	VEXTRACTF128 $1, Y0, X1
	VADDPS X1, X0, X0
	VSHUFPS $0x4E, X0, X0, X1
	VADDPS X1, X0, X0
	VSHUFPS $0x01, X0, X0, X1
	VADDSS X1, X0, X0

	TESTQ CX, CX
	JZ done_i8

scalar_loop_i8:
	MOVBLSX 0(DI), AX
	VCVTSI2SSL AX, X2, X2
	VMULSS 0(SI), X2, X2
	VADDSS X2, X0, X0
	ADDQ $4, SI
	INCQ DI
	DECQ CX
	JNZ scalar_loop_i8

done_i8:
	VZEROUPPER
	VMOVSS X0, ret+48(FP)
	RET
