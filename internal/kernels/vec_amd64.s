// func dotProductASM_F32(x, y []float32) float32
TEXT ·dotProductASM_F32(SB), NOSPLIT, $0-52
	MOVQ x_base+0(FP), SI
	MOVQ x_len+8(FP), CX
	MOVQ y_base+24(FP), DI
	MOVQ y_len+32(FP), DX

	CMPQ DX, CX
	JGE have_len_dp_f32
	MOVQ DX, CX
have_len_dp_f32:
	VZEROUPPER
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1

loop16_dp_f32:
	CMPQ CX, $16
	JL loop8_dp_f32
	VMOVUPS 0(SI), Y2
	VMOVUPS 32(SI), Y3
	VFMADD231PS 0(DI), Y2, Y0
	VFMADD231PS 32(DI), Y3, Y1
	ADDQ $64, SI
	ADDQ $64, DI
	SUBQ $16, CX
	JMP loop16_dp_f32

loop8_dp_f32:
	CMPQ CX, $8
	JL reduce_dp_f32
	VMOVUPS 0(SI), Y2
	VFMADD231PS 0(DI), Y2, Y0
	ADDQ $32, SI
	ADDQ $32, DI
	SUBQ $8, CX

reduce_dp_f32:
	VADDPS Y1, Y0, Y0
	VEXTRACTF128 $1, Y0, X1
	VADDPS X1, X0, X0
	VSHUFPS $0x4E, X0, X0, X1
	VADDPS X1, X0, X0
	VSHUFPS $0x01, X0, X0, X1
	VADDSS X1, X0, X0

	TESTQ CX, CX
	JZ done_dp_f32

scalar_loop_dp_f32:
	VMOVSS 0(SI), X2
	VMULSS 0(DI), X2, X2
	VADDSS X2, X0, X0
	ADDQ $4, SI
	ADDQ $4, DI
	DECQ CX
	JNZ scalar_loop_dp_f32

done_dp_f32:
	VZEROUPPER
	VMOVSS X0, ret+48(FP)
	RET

