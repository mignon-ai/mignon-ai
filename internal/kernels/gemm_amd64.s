#include "textflag.h"

// func gemmKernel6x16ASM(k int, a *float32, rsA, csA int, b *float32, ldb int, c *float32, ldc int)
//
// Registers: Y0..Y11 hold the 6×16 C tile (two vectors per row), Y12/Y13 the current B row,
// Y14/Y15 the broadcast A values. SI walks A rows 0-2 and BX rows 3-5 (row offsets R8, 2·R8).
TEXT ·gemmKernel6x16ASM(SB), NOSPLIT, $0-64
	MOVQ k+0(FP), CX
	MOVQ a+8(FP), SI
	MOVQ rsA+16(FP), R8
	SHLQ $2, R8
	MOVQ csA+24(FP), R9
	SHLQ $2, R9
	MOVQ b+32(FP), DI
	MOVQ ldb+40(FP), R10
	SHLQ $2, R10
	MOVQ c+48(FP), DX
	MOVQ ldc+56(FP), R11
	SHLQ $2, R11
	LEAQ (SI)(R8*2), BX
	ADDQ R8, BX

	// Load the C tile.
	MOVQ DX, R12
	VMOVUPS 0(R12), Y0
	VMOVUPS 32(R12), Y1
	ADDQ R11, R12
	VMOVUPS 0(R12), Y2
	VMOVUPS 32(R12), Y3
	ADDQ R11, R12
	VMOVUPS 0(R12), Y4
	VMOVUPS 32(R12), Y5
	ADDQ R11, R12
	VMOVUPS 0(R12), Y6
	VMOVUPS 32(R12), Y7
	ADDQ R11, R12
	VMOVUPS 0(R12), Y8
	VMOVUPS 32(R12), Y9
	ADDQ R11, R12
	VMOVUPS 0(R12), Y10
	VMOVUPS 32(R12), Y11

	TESTQ CX, CX
	JLE gemm_store

gemm_loop:
	VMOVUPS 0(DI), Y12
	VMOVUPS 32(DI), Y13
	VBROADCASTSS (SI), Y14
	VFMADD231PS Y12, Y14, Y0
	VFMADD231PS Y13, Y14, Y1
	VBROADCASTSS (SI)(R8*1), Y15
	VFMADD231PS Y12, Y15, Y2
	VFMADD231PS Y13, Y15, Y3
	VBROADCASTSS (SI)(R8*2), Y14
	VFMADD231PS Y12, Y14, Y4
	VFMADD231PS Y13, Y14, Y5
	VBROADCASTSS (BX), Y15
	VFMADD231PS Y12, Y15, Y6
	VFMADD231PS Y13, Y15, Y7
	VBROADCASTSS (BX)(R8*1), Y14
	VFMADD231PS Y12, Y14, Y8
	VFMADD231PS Y13, Y14, Y9
	VBROADCASTSS (BX)(R8*2), Y15
	VFMADD231PS Y12, Y15, Y10
	VFMADD231PS Y13, Y15, Y11
	ADDQ R9, SI
	ADDQ R9, BX
	ADDQ R10, DI
	DECQ CX
	JNZ gemm_loop

gemm_store:
	MOVQ DX, R12
	VMOVUPS Y0, 0(R12)
	VMOVUPS Y1, 32(R12)
	ADDQ R11, R12
	VMOVUPS Y2, 0(R12)
	VMOVUPS Y3, 32(R12)
	ADDQ R11, R12
	VMOVUPS Y4, 0(R12)
	VMOVUPS Y5, 32(R12)
	ADDQ R11, R12
	VMOVUPS Y6, 0(R12)
	VMOVUPS Y7, 32(R12)
	ADDQ R11, R12
	VMOVUPS Y8, 0(R12)
	VMOVUPS Y9, 32(R12)
	ADDQ R11, R12
	VMOVUPS Y10, 0(R12)
	VMOVUPS Y11, 32(R12)
	VZEROUPPER
	RET
